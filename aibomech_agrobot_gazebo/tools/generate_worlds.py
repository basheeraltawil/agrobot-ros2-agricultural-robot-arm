#!/usr/bin/env python3
"""Generate the agricultural scenario worlds for Gazebo Sim (Fortress).

For every world this writes
  worlds/<name>.sdf             the world
  config/<name>_objects.yaml    ground truth of all task objects (used for
                                evaluation and the ground-truth perception mode)
  config/<name>_bridge.yaml     ros_gz_bridge topics (camera, clock, grasp joints)

Grasping in simulation: each graspable object carries a DetachableJoint
towards the gripper link (link_4). Gazebo creates such joints attached, so
sim_manager.py detaches them all while the simulation is still paused.
Fruit and weeds are additionally held by the plant / soil through a second
DetachableJoint, released when the robot cuts or pulls them.

The layout depends on the robot geometry: the arm mounting plate is at
MOUNT_HEIGHT above the floor, the rail runs along x at y = 0 and the crop
row is on the +y side.

    python3 tools/generate_worlds.py
"""
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
MOUNT_HEIGHT = 0.85
ROBOT = 'agrobot'
GRIPPER_LINK = 'link_4'

# Colours (r g b)
RED_RIPE = (0.78, 0.04, 0.05)
UNRIPE = (0.72, 0.82, 0.45)
LEAF = (0.14, 0.45, 0.10)
LEAF_DARK = (0.08, 0.32, 0.07)
CALYX = (0.10, 0.50, 0.12)
WEED = (0.52, 0.10, 0.46)
LETTUCE = (0.45, 0.78, 0.25)
SOIL = (0.30, 0.20, 0.12)
SUBSTRATE = (0.38, 0.26, 0.15)
GUTTER = (0.92, 0.92, 0.92)
STEEL = (0.55, 0.57, 0.60)
TRAY = (0.10, 0.10, 0.11)
POT = (0.75, 0.35, 0.15)
BENCH = (0.62, 0.63, 0.60)


def material(rgb, emissive=0.0):
    r, g, b = rgb
    e = f'<emissive>{r*emissive:.3f} {g*emissive:.3f} {b*emissive:.3f} 1</emissive>' if emissive else ''
    return (f'<material><ambient>{r:.3f} {g:.3f} {b:.3f} 1</ambient>'
            f'<diffuse>{r:.3f} {g:.3f} {b:.3f} 1</diffuse>'
            f'<specular>0.1 0.1 0.1 1</specular>{e}</material>')


def pose(x=0, y=0, z=0, roll=0, pitch=0, yaw=0):
    return f'<pose>{x:.4f} {y:.4f} {z:.4f} {roll:.4f} {pitch:.4f} {yaw:.4f}</pose>'


def box(size):
    return f'<box><size>{size[0]:.4f} {size[1]:.4f} {size[2]:.4f}</size></box>'


def cylinder(radius, length):
    return f'<cylinder><radius>{radius:.4f}</radius><length>{length:.4f}</length></cylinder>'


def sphere(radius):
    return f'<sphere><radius>{radius:.4f}</radius></sphere>'


def ellipsoid(rx, ry, rz):
    return f'<ellipsoid><radii>{rx:.4f} {ry:.4f} {rz:.4f}</radii></ellipsoid>'


def visual(name, geometry, rgb, p='', emissive=0.0):
    return f'<visual name="{name}">{p}<geometry>{geometry}</geometry>{material(rgb, emissive)}</visual>'


def collision(name, geometry, p='', mu=1.0):
    return (f'<collision name="{name}_collision">{p}<geometry>{geometry}</geometry>'
            f'<surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface></collision>')


def inertial(mass, size):
    x, y, z = size
    return (f'<inertial><mass>{mass}</mass><inertia>'
            f'<ixx>{mass*(y*y+z*z)/12:.3e}</ixx><iyy>{mass*(x*x+z*z)/12:.3e}</iyy>'
            f'<izz>{mass*(x*x+y*y)/12:.3e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz>'
            f'</inertia></inertial>')


def static_model(name, p, body):
    return f'<model name="{name}"><static>true</static>{p}<link name="link">{body}</link></model>'


def grasp_plugin(obj):
    """DetachableJoint object <-> gripper, driven by the task over ROS topics."""
    return (f'<plugin filename="ignition-gazebo-detachable-joint-system" '
            f'name="ignition::gazebo::systems::DetachableJoint">'
            f'<parent_link>link</parent_link><child_model>{ROBOT}</child_model>'
            f'<child_link>{GRIPPER_LINK}</child_link>'
            f'<attach_topic>/agrobot/sim/{obj}/attach_gripper</attach_topic>'
            f'<detach_topic>/agrobot/sim/{obj}/detach_gripper</detach_topic>'
            f'<suppress_child_warning>true</suppress_child_warning></plugin>')


def anchor_plugin(parent_link, obj):
    """DetachableJoint holding an object on its plant / in the soil."""
    return (f'<plugin filename="ignition-gazebo-detachable-joint-system" '
            f'name="ignition::gazebo::systems::DetachableJoint">'
            f'<parent_link>{parent_link}</parent_link><child_model>{obj}</child_model>'
            f'<child_link>link</child_link>'
            f'<detach_topic>/agrobot/sim/{obj}/detach_anchor</detach_topic></plugin>')


def world_header(name):
    return f'''<?xml version="1.0"?>
<!-- Generated by tools/generate_worlds.py - edit the generator, not this file. -->
<sdf version="1.8">
<world name="{name}">
  <physics name="1ms" type="ignored">
    <max_step_size>0.001</max_step_size>
    <real_time_factor>1.0</real_time_factor>
  </physics>
  <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
  <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
  <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
  <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
    <render_engine>ogre2</render_engine>
  </plugin>
  <gravity>0 0 -9.81</gravity>
  <scene>
    <ambient>0.55 0.55 0.55 1</ambient>
    <background>0.72 0.82 0.92 1</background>
    <shadows>true</shadows>
  </scene>
  <light type="directional" name="sun">
    <cast_shadows>true</cast_shadows>
    <pose>0 0 10 0 0 0</pose>
    <diffuse>0.85 0.85 0.82 1</diffuse>
    <specular>0.2 0.2 0.2 1</specular>
    <direction>-0.3 0.4 -0.9</direction>
  </light>
  <light type="directional" name="greenhouse_diffuse">
    <cast_shadows>false</cast_shadows>
    <pose>0 0 10 0 0 0</pose>
    <diffuse>0.35 0.35 0.35 1</diffuse>
    <specular>0 0 0 1</specular>
    <direction>0.2 -0.5 -0.8</direction>
  </light>
  <model name="floor">
    <static>true</static>
    <link name="link">
      {collision("c", '<plane><normal>0 0 1</normal><size>20 20</size></plane>')}
      {visual("v", '<plane><normal>0 0 1</normal><size>20 20</size></plane>', (0.52, 0.52, 0.50))}
    </link>
  </model>
'''


def greenhouse_frame(x_min, x_max):
    """Posts and roof beams, purely visual context."""
    parts = []
    for i, x in enumerate([x_min + k * 1.6 for k in range(int((x_max - x_min) / 1.6) + 1)]):
        for side, y in (('a', -0.9), ('b', 1.4)):
            parts.append(static_model(
                f'post_{i}{side}', pose(x, y, 1.5),
                visual('v', box((0.06, 0.06, 3.0)), STEEL)))
    return '\n'.join(parts)


class World:
    def __init__(self, name, description):
        self.name = name
        self.description = description
        self.sdf = [world_header(name)]
        self.objects = []    # ground truth
        self.grasp = []      # objects with a gripper joint
        self.anchored = []   # objects with an anchor joint

    def add(self, text):
        self.sdf.append(text)

    def write(self):
        self.sdf.append('</world>\n</sdf>\n')
        with open(os.path.join(PKG, 'worlds', f'{self.name}.sdf'), 'w') as fh:
            fh.write('\n'.join(self.sdf))
        with open(os.path.join(PKG, 'config', f'{self.name}_objects.yaml'), 'w') as fh:
            fh.write(f'# Generated by tools/generate_worlds.py\n# {self.description}\n')
            fh.write(f'world: {self.name}\nmount_height: {MOUNT_HEIGHT}\nobjects:\n')
            for o in self.objects:
                fh.write(f"  - {{name: {o['name']}, type: {o['type']}, "
                         f"x: {o['x']:.4f}, y: {o['y']:.4f}, z: {o['z']:.4f}"
                         + ''.join(f', {k}: {v}' for k, v in o.items()
                                   if k not in ('name', 'type', 'x', 'y', 'z')) + '}\n')
        with open(os.path.join(PKG, 'config', f'{self.name}_bridge.yaml'), 'w') as fh:
            fh.write('# Generated by tools/generate_worlds.py\n')
            fh.write(bridge_entries(self.name, self.grasp, self.anchored))
        print(f'{self.name}: {len(self.objects)} objects')


def bridge_entry(ros, gz, ros_type, gz_type, direction):
    return (f'- ros_topic_name: "{ros}"\n  gz_topic_name: "{gz}"\n'
            f'  ros_type_name: "{ros_type}"\n  gz_type_name: "{gz_type}"\n  direction: {direction}\n')


def bridge_entries(world, grasp, anchored):
    out = [
        bridge_entry('/clock', '/clock', 'rosgraph_msgs/msg/Clock', 'ignition.msgs.Clock', 'GZ_TO_ROS'),
        # Same topic names as the realsense2_camera driver on the real robot.
        bridge_entry('/camera/color/image_raw', '/agrobot/camera/image',
                     'sensor_msgs/msg/Image', 'ignition.msgs.Image', 'GZ_TO_ROS'),
        bridge_entry('/camera/color/camera_info', '/agrobot/camera/camera_info',
                     'sensor_msgs/msg/CameraInfo', 'ignition.msgs.CameraInfo', 'GZ_TO_ROS'),
        bridge_entry('/camera/aligned_depth_to_color/image_raw', '/agrobot/camera/depth_image',
                     'sensor_msgs/msg/Image', 'ignition.msgs.Image', 'GZ_TO_ROS'),
        bridge_entry('/camera/depth/color/points', '/agrobot/camera/points',
                     'sensor_msgs/msg/PointCloud2', 'ignition.msgs.PointCloudPacked', 'GZ_TO_ROS'),
        bridge_entry('/agrobot/sim/model_poses', f'/world/{world}/dynamic_pose/info',
                     'tf2_msgs/msg/TFMessage', 'ignition.msgs.Pose_V', 'GZ_TO_ROS'),
    ]
    for obj in grasp:
        for action in ('attach_gripper', 'detach_gripper'):
            topic = f'/agrobot/sim/{obj}/{action}'
            out.append(bridge_entry(topic, topic, 'std_msgs/msg/Empty', 'ignition.msgs.Empty', 'ROS_TO_GZ'))
    for obj in anchored:
        topic = f'/agrobot/sim/{obj}/detach_anchor'
        out.append(bridge_entry(topic, topic, 'std_msgs/msg/Empty', 'ignition.msgs.Empty', 'ROS_TO_GZ'))
    return ''.join(out)


