# Scenario 3: raised bed with lettuce and weeds (precision weeding)
# --------------------------------------------------------------------------
def weeding_bed(rng):
    w = World('weeding_bed', 'Raised lettuce bed with purple broadleaf weeds between the crop plants.')
    soil_z = MOUNT_HEIGHT - 0.09
    w.add(greenhouse_frame(-0.4, 3.0))
    bed_x0, bed_x1, bed_y0, bed_y1 = 0.10, 2.70, 0.16, 0.44
    bx, by = (bed_x0 + bed_x1) / 2, (bed_y0 + bed_y1) / 2
    bed = (f'<link name="bed">{inertial(80.0, (bed_x1 - bed_x0, bed_y1 - bed_y0, 0.3))}'
           + visual('soil', box((bed_x1 - bed_x0, bed_y1 - bed_y0, 0.02)), SOIL)
           + collision('soil', box((bed_x1 - bed_x0, bed_y1 - bed_y0, 0.02)))
           + visual('frame_front', box((bed_x1 - bed_x0, 0.02, 0.06)), (0.45, 0.33, 0.2),
                    pose(0, -(bed_y1 - bed_y0) / 2, -0.02))
           + visual('frame_back', box((bed_x1 - bed_x0, 0.02, 0.06)), (0.45, 0.33, 0.2),
                    pose(0, (bed_y1 - bed_y0) / 2, -0.02)))
    for k, (dx, dy) in enumerate([(-1.25, -0.12), (1.25, -0.12), (-1.25, 0.12), (1.25, 0.12)]):
        bed += visual(f'leg_{k}', box((0.05, 0.05, soil_z - 0.04)), STEEL, pose(dx, dy, -(soil_z - 0.04) / 2 - 0.01))

    crops = []
    for i, cx in enumerate([0.30 + k * 0.30 for k in range(8)]):
        cy = 0.35 + rng.uniform(-0.01, 0.01)
        crops.append((cx, cy))
        bed += lettuce_visual(f'lettuce_{i}', cx - bx, cy - by, 0.01, rng)
        w.objects.append({'name': f'lettuce_{i}', 'type': 'lettuce', 'x': cx, 'y': cy, 'z': soil_z + 0.01})
    bed += '</link>'

    weeds, plugins = [], []
    while len(weeds) < 8:
        x, y = rng.uniform(0.35, 2.35), rng.uniform(0.21, 0.29)
        if all(math.dist((x, y), c) > 0.10 for c in crops) and all(math.dist((x, y), q) > 0.09 for q in weeds):
            weeds.append((x, y))
    weeds.sort()
    for k, (x, y) in enumerate(weeds):
        name = f'weed_{k}'
        z = soil_z + 0.01
        w.add(weed_model(name, x, y, z, rng))
        plugins.append(anchor_plugin('bed', name))
        w.grasp.append(name)
        w.anchored.append(name)
        w.objects.append({'name': name, 'type': 'weed', 'x': x, 'y': y, 'z': z})
    w.add(f'<model name="raised_bed"><static>true</static>{pose(bx, by, soil_z)}{bed}'
          + ''.join(plugins) + '</model>')
    w.write()


def lettuce_visual(name, x, y, z, rng):
    out = visual(f'{name}_heart', ellipsoid(0.03, 0.03, 0.025), LETTUCE, pose(x, y, z + 0.025))
    for k in range(7):
        a = k * 2 * math.pi / 7 + rng.uniform(-0.2, 0.2)
        out += visual(f'{name}_leaf{k}', ellipsoid(0.04, 0.022, 0.006), LETTUCE if k % 2 else (0.35, 0.68, 0.2),
                      pose(x + 0.03 * math.cos(a), y + 0.03 * math.sin(a), z + 0.02, 0, -0.5, a))
    return out


def weed_model(name, x, y, z, rng):
    body = (inertial(0.008, (0.02, 0.02, 0.04))
            + visual('stem', cylinder(0.003, 0.035), (0.35, 0.12, 0.25), pose(0, 0, 0.0175))
            + collision('core', cylinder(0.003, 0.035), pose(0, 0, 0.0175)))
    for k in range(5):
        a = k * 2 * math.pi / 5 + rng.uniform(-0.3, 0.3)
        body += visual(f'leaf{k}', ellipsoid(0.016, 0.008, 0.002), WEED,
                       pose(0.014 * math.cos(a), 0.014 * math.sin(a), 0.006 + 0.004 * (k % 2), 0, -0.3, a))
    body += visual('top', ellipsoid(0.008, 0.008, 0.004), WEED, pose(0, 0, 0.036))
    return (f'<model name="{name}">{pose(x, y, z)}<link name="link">{body}</link>'
            + grasp_plugin(name) + '</model>')


