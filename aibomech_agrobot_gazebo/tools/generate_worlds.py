# Scenario 1: table-top strawberries in a greenhouse (harvesting, inspection)
# --------------------------------------------------------------------------
def strawberry_greenhouse(rng):
    w = World('strawberry_greenhouse',
              'Elevated strawberry gutter along the rail, ripe and unripe fruit hanging over the aisle edge.')
    m = MOUNT_HEIGHT
    gutter_front, gutter_back = 0.215, 0.415
    gutter_bottom, gutter_top = m + 0.07, m + 0.15
    x0, x1 = -0.3, 3.3
    w.add(greenhouse_frame(-0.4, 3.4))
    gy = (gutter_front + gutter_back) / 2
    gz = (gutter_bottom + gutter_top) / 2
    body = (visual('gutter', box((x1 - x0, gutter_back - gutter_front, gutter_top - gutter_bottom)), GUTTER)
            + collision('gutter', box((x1 - x0, gutter_back - gutter_front, gutter_top - gutter_bottom)))
            + visual('substrate', box((x1 - x0, 0.16, 0.01)), SUBSTRATE,
                     pose(0, 0, (gutter_top - gutter_bottom) / 2 + 0.005)))
    for k, x in enumerate([x0 + 0.2 + i * 0.8 for i in range(5)]):
        h = gutter_bottom
        body += visual(f'leg_{k}', box((0.04, 0.04, h)), STEEL, pose(x - (x0 + x1) / 2, 0, -gz + h / 2))
    w.add(static_model('gutter', pose((x0 + x1) / 2, gy, gz), body))

    fruit_id = 0
    for p, px in enumerate([0.40, 0.80, 1.20, 1.60, 2.00, 2.40]):
        crown_z = gutter_top + 0.02
        plant = f'plant_{p}'
        links = [f'<link name="crown">{inertial(0.3, (0.05, 0.05, 0.05))}'
                 + visual('crown', cylinder(0.02, 0.03), LEAF_DARK)]
        # Trifoliate leaves on petioles, spread over the gutter.
        for leaf in range(6):
            ang = rng.uniform(0, 2 * math.pi)
            r = rng.uniform(0.04, 0.09)
            lx, ly = r * math.cos(ang), abs(r * math.sin(ang)) * 0.8 + 0.02
            lz = rng.uniform(0.05, 0.12)
            links.append(visual(f'petiole_{leaf}', cylinder(0.002, lz), CALYX, pose(lx * 0.5, ly * 0.5, lz / 2)))
            for t in range(3):
                a = ang + (t - 1) * 0.7
                links.append(visual(f'leaf_{leaf}_{t}', ellipsoid(0.028, 0.018, 0.003),
                                    LEAF if t != 1 else LEAF_DARK,
                                    pose(lx + 0.02 * math.cos(a), ly + 0.02 * math.sin(a), lz, 0.2, 0.15, a)))
        plugins = []
        n_fruit = rng.choice([3, 3, 4])
        offsets = sorted(rng.sample([-0.09, -0.06, -0.03, 0.0, 0.03, 0.06, 0.09], n_fruit))
        for dx in offsets:
            ripe = rng.random() < 0.65
            name = f'fruit_{fruit_id}'
            fruit_id += 1
            fx = px + dx + rng.uniform(-0.008, 0.008)
            fy = gutter_front - 0.022 + rng.uniform(-0.004, 0.004)
            fz = m + rng.uniform(0.020, 0.045)
            # Peduncle from the gutter edge down to the calyx (stays on the plant).
            top = (fx - px, gutter_front - gy + 0.105, gutter_top - crown_z + 0.005)
            bot = (fx - px, fy - gy + 0.105, fz + 0.016 - crown_z)
            length = math.dist(top, bot)
            pitch = math.atan2(top[1] - bot[1], top[2] - bot[2])
            links.append(visual(f'peduncle_{name}', cylinder(0.0015, length), CALYX,
                                pose((top[0] + bot[0]) / 2, (top[1] + bot[1]) / 2, (top[2] + bot[2]) / 2,
                                     -pitch, 0, 0)))
            plugins.append(anchor_plugin('crown', name))
            w.add(fruit_model(name, fx, fy, fz, ripe))
            w.grasp.append(name)
            w.anchored.append(name)
            w.objects.append({'name': name, 'type': 'strawberry_ripe' if ripe else 'strawberry_unripe',
                              'x': fx, 'y': fy, 'z': fz, 'plant': plant})
        links.append('</link>')
        # Static: a joint to "world" in more than one model freezes the robot's
        # rail joint in Gazebo Fortress (gz-physics dartsim).
        w.add(f'<model name="{plant}"><static>true</static>{pose(px, gy - 0.105, crown_z)}'
              + ''.join(links) + ''.join(plugins) + '</model>')
        w.objects.append({'name': plant, 'type': 'plant', 'x': px, 'y': gy - 0.105, 'z': crown_z})
    w.write()


def fruit_model(name, x, y, z, ripe):
    colour = RED_RIPE if ripe else UNRIPE
    # Collision is a small core so the jaws never push the fruit (see module doc).
    return (f'<model name="{name}">{pose(x, y, z)}<link name="link">'
            + inertial(0.015, (0.019, 0.019, 0.024))
            + visual('berry', ellipsoid(0.0095, 0.0095, 0.012), colour, emissive=0.15 if ripe else 0.0)
            + visual('calyx', cylinder(0.009, 0.003), CALYX, pose(0, 0, 0.012))
            + collision('core', sphere(0.004))
            + '</link>' + grasp_plugin(name) + '</model>')


